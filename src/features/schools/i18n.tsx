type LanguageContextValue = { language: AppLanguage; setLanguage: (language: AppLanguage) => void; t: (key: string) => string };
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>(() => localStorage.getItem('mya-language') === 'fr' ? 'fr' : 'en');
  const setLanguage = useCallback((next: AppLanguage) => { setLanguageState(next); localStorage.setItem('mya-language', next); }, []);
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  const translate = useCallback((key: string) => {
    if (language !== 'fr') return key;
    if (frenchUi[key]) return frenchUi[key];
    const gpa = key.match(/^GPA (.+) or higher$/);
    if (gpa) return `GPA de ${gpa[1]} ou plus`;
    const cost = key.match(/^Extra cost up to €(.+)$/);
    if (cost) return `Frais supplémentaires jusqu’à ${cost[1]} €`;
    const instructionLanguage = key.match(/^Language: (.+)$/);
    if (instructionLanguage) return `Langue : ${translatedData(instructionLanguage[1], 'languages', language)}`;
    return key;
  }, [language]);
  const value = useMemo<LanguageContextValue>(() => ({ language, setLanguage, t: translate }), [language, setLanguage, translate]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('useLanguage must be used within LanguageProvider');
  return value;
}

export function translatedData(value: string, group: DataTranslationGroup, language: AppLanguage) {
  if (language === 'en') return value;
  const map = myaTranslations[group] as Record<string, string>;
  return map[value] || value;
}

export function translatedSchoolName(name: string, nameFr: string | undefined, language: AppLanguage) {
  return language === 'fr' && nameFr ? nameFr : name;
}

export function translatedLanguageList(value: string, language: AppLanguage) {
  if (language === 'en' || !value) return value;
  return value.split(/\s*(?:,|\/|;|\band\b|\bet\b)\s*/i).map((part) => translatedData(part, 'languages', language)).join(', ');
}
